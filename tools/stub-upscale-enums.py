#!/usr/bin/env python3
"""Generate the fps/upscale enums for the offline `settings` gate.

`src/view_settings.rs` names five enums that are declared in `src/main.rs`:
`FrameGenMethod`, `FrameMultiplier`, `LatencyMode`, `UpscaleMethod` and
`UpscaleQuality`. `main.rs` is not compilable offline (it is `winit` + `wgpu` +
`egui`), so this gate needs them declared somewhere else.

That makes the stub a **second copy of the file format**, because the setting
persists through each enum's `token()` and is read back through its `parse()`.
A stub that drifts from the real enum writes a spelling the viewer cannot read
-- silently, since an unknown token falls back to the default.

So the stub is generated from `main.rs` rather than written by hand, the
variants and `#[default]` come from parsing it, and `--check` fails when the
generated text is not what is on disk. `settings` runs it, and CI's settings
step runs it too.

Usage:
    stub-upscale-enums.py <main.rs> <out.rs>          write the stub
    stub-upscale-enums.py <main.rs> <out.rs> --check  fail if it is stale
"""
import os
import re
import sys

# Variant name -> (token, label, parse aliases). The token is the persisted
# spelling and only these five enums have one; the values come from `main.rs`'s
# own `token()`/`label()`/`parse()` bodies, read rather than retyped.
ENUMS = {
    "FrameGenMethod": dict(tokens=True, parse=True),
    "FrameMultiplier": dict(tokens=True, parse=True),
    "LatencyMode": dict(tokens=True, parse=True),
    "UpscaleMethod": dict(tokens=True, parse=True),
    "UpscaleQuality": dict(tokens=True, parse=True),
}


def enum_block(src, name):
    m = re.search(r"pub enum %s \{(.*?)\n\}" % name, src, re.S)
    if not m:
        raise SystemExit("no `pub enum %s` in main.rs" % name)
    return m.group(1)


def impl_block(src, name):
    m = re.search(r"impl %s \{(.*?)\n\}" % name, src, re.S)
    if not m:
        raise SystemExit("no `impl %s` in main.rs" % name)
    return m.group(1)


def variants(body):
    """Variant names, in declaration order, with which one is `#[default]`."""
    out = []
    default = False
    for line in body.splitlines():
        t = line.strip()
        if t.startswith("#[default]"):
            default = True
        elif re.fullmatch(r"[A-Za-z][A-Za-z0-9]*,", t):
            out.append((t[:-1], default))
            default = False
    return out


def arms(body, method):
    """`Variant => "string"` pairs from one method body."""
    m = re.search(r"fn %s\(self\).*?\{(.*?)\n    \}" % method, body, re.S)
    if not m:
        return {}
    return dict(re.findall(r"(?:Self::)?([A-Za-z0-9]+)\s*=>\s*\"([^\"]*)\"", m.group(1)))


def parse_arms(body):
    """`"spelling" | "spelling" => Some(Self::Variant)` -> variant: [spellings]."""
    m = re.search(r"fn parse\(.*?\{(.*?)\n    \}", body, re.S)
    if not m:
        return {}
    out = {}
    for pat, var in re.findall(
        r'((?:"[^"]*"(?:\s*\|\s*)?)+)\s*=>\s*Some\(Self::([A-Za-z0-9]+)\)', m.group(1)
    ):
        out.setdefault(var, []).extend(re.findall(r'"([^"]*)"', pat))
    return out


def generate(src):
    parts = [
        "// Generated by tools/stub-upscale-enums.py from src/main.rs -- do not edit.",
        "// These are the settings-file spellings; `settings` regenerates and checks",
        "// them, so a variant added to main.rs shows up here or fails the gate.",
        "#![allow(dead_code)]",
        "",
    ]
    for name in ENUMS:
        vs = variants(enum_block(src, name))
        # `ALL` in main.rs is the authority on order; the declaration is the
        # authority on what exists. They agree, and the gate asserts it.
        impl = impl_block(src, name)
        m = re.search(r"pub const ALL: \[Self; \d+\] = \[(.*?)\];", impl, re.S)
        if m:
            listed = re.findall(r"Self::([A-Za-z0-9]+)", m.group(1))
            declared = [v for v, _ in vs]
            if listed != declared and sorted(listed) != sorted(declared):
                # Different sets is a real problem: ALL would iterate a variant
                # the stub does not have.
                raise SystemExit(
                    "%s: ALL is %s but the enum declares %s" % (name, listed, declared)
                )
            # Same set in a different order is allowed and is noted, not fixed:
            # `LatencyMode::ALL` is `[Vsync, Reflex, Xell]` while the enum
            # declares `Vsync, Xell, Reflex`, which is a deliberate grouping in
            # main.rs (Reflex beside the other decoupled option). The stub keeps
            # declaration order, so a UI row order in the real binary cannot be
            # mistaken for the persisted format.
        default = next((v for v, d in vs if d), vs[0][0])
        tokens = arms(impl, "token")
        labels = arms(impl, "label")
        parses = parse_arms(impl)
        parts.append("#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]")
        parts.append("pub enum %s {" % name)
        for v, d in vs:
            if d:
                parts.append("    #[default]")
            parts.append("    %s," % v)
        parts.append("}")
        parts.append("impl %s {" % name)
        parts.append(
            "    pub const ALL: [Self; %d] = [%s];"
            % (len(vs), ", ".join("Self::" + v for v, _ in vs))
        )
        parts.append("    pub fn token(self) -> &'static str {")
        parts.append("        match self {")
        for v, _ in vs:
            parts.append('            Self::%s => "%s",' % (v, tokens.get(v, v.lower())))
        parts.append("        }")
        parts.append("    }")
        parts.append("    pub fn label(self) -> &'static str {")
        parts.append("        match self {")
        for v, _ in vs:
            parts.append('            Self::%s => "%s",' % (v, labels.get(v, v)))
        parts.append("        }")
        parts.append("    }")
        parts.append("    pub fn parse(text: &str) -> Option<Self> {")
        parts.append("        match text.trim().to_ascii_lowercase().as_str() {")
        for v, _ in vs:
            spellings = parses.get(v)
            if not spellings:
                raise SystemExit("%s::%s has no parse arm in main.rs" % (name, v))
            pats = " | ".join('"%s"' % s for s in spellings)
            parts.append("            %s => Some(Self::%s)," % (pats, v))
        parts.append("            _ => None,")
        parts.append("        }")
        parts.append("    }")
        if name == "FrameMultiplier":
            # `view_settings` persists this one as a token and the renderer reads
            # the number; the multiplier is the only non-spelling method used.
            body = re.search(
                r"pub fn multiplier\(self\) -> u32 \{\s*match self \{(.*?)\n    \}",
                impl,
                re.S,
            )
            if body:
                parts.append("    pub fn multiplier(self) -> u32 {")
                parts.append("        match self {")
                for arm in re.findall(r"Self::(\w+) => (\d+)", body.group(1)):
                    parts.append("            Self::%s => %s," % arm)
                parts.append("        }")
                parts.append("    }")
        parts.append("}")
        parts.append("")
    return "\n".join(parts)


def main(argv):
    if len(argv) < 3:
        return "usage: stub-upscale-enums.py <main.rs> <out.rs> [--check]"
    src = open(argv[1], encoding="utf-8").read()
    text = generate(src)
    check = "--check" in argv[3:]
    if check:
        try:
            current = open(argv[2], encoding="utf-8").read()
        except OSError:
            return "%s: missing; run tools/stub-upscale-enums.py %s %s" % (
                argv[2],
                argv[1],
                argv[2],
            )
        if current != text:
            if os.environ.get("GITHUB_ACTIONS"):
                print("::error file=%s::stale" % argv[2])
            return (
                "%s is stale: src/main.rs's enums changed. The settings file "
                "persists these spellings, so a stale stub tests the wrong "
                "format. Regenerate with tools/stub-upscale-enums.py %s %s"
                % (argv[2], argv[1], argv[2])
            )
        return None
    with open(argv[2], "w", encoding="utf-8") as f:
        f.write(text)
    return None


if __name__ == "__main__":
    problem = main(sys.argv)
    if problem:
        print(problem, file=sys.stderr)
        sys.exit(1)
